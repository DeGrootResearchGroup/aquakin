    def add_unit(self, unit: Unit) -> None:
        """Register a unit.

        Units may be added in any order: the plant computes the RHS evaluation
        order itself by topologically sorting the connection graph at solve time
        (recycles are the graph back-edges, detected automatically -- you do not
        have to add a downstream unit before its upstream consumer). The add
        order is used only as a deterministic tie-break for the sort and to order
        the per-model parameter blocks.
        """
        if unit.name in self.units:
            raise ValueError(f"Unit '{unit.name}' already added")
        self._check_unit_name(unit)
        self.units[unit.name] = unit
        self._insertion_order.append(unit.name)
        # Seed the evaluation order with the insertion order so it is non-empty
        # before the first solve (helpers that just enumerate units read it);
        # _finalize_topology() reorders it into a valid topological order.
        self._unit_order.append(unit.name)
        self._structure_changed()

    _structure_changed = structure_changed

    def _check_unit_name(self, unit) -> None:
        """Refuse a unit name or port name the plant's addressing cannot read.

        Endpoints are ``"unit.port"`` and parameters ``"<model>.<param>"`` /
        ``"<unit>.<setpoint>"``, so a dot (or whitespace, or ``->``) in a name
        makes an endpoint ambiguous, and a unit named like one of the plant's
        models would share its parameter keys (``"asm1.muH"`` could then name a
        splitter's flow setpoint instead of the kinetic rate).
        """
        check_name("unit", unit.name)
        for port in [*unit.input_ports, *unit.output_ports]:
            check_name(f"port of unit '{unit.name}': port", port)
        model = getattr(unit, "model", None)
        if model is not None:
            check_name("model", model.name)
        if unit.name in self.influents:
            raise WiringError(f"unit name '{unit.name}' is already the name of an influent")
        if unit.name in self.named_streams:
            raise WiringError(f"unit name '{unit.name}' is already the name of a stream")
        models = {
            u.model.name
            for u in [*self.units.values(), unit]
            if getattr(u, "model", None) is not None
        }
        if unit.name in models:
            raise WiringError(
                f"unit name '{unit.name}' is the name of a model in this plant; parameter "
                f"names '<model>.<param>' and '<unit>.<setpoint>' would collide. Rename the unit."
            )
        model = getattr(unit, "model", None)
        if model is not None and model.name in self.units:
            raise WiringError(
                f"unit '{unit.name}' uses model '{model.name}', which is also a unit name in this "
                f"plant; parameter names would collide. Rename that unit."
            )

    def add_influent(
        self,
        name: str,
        series: InfluentSeries,
        to: str | None = None,
        *,
        translator: StateTranslator | None = None,
    ) -> None:
        """Register an external time-varying influent stream, optionally wiring it.

        Parameters
        ----------
        name : str
            Identifier for this influent (used in stream keys and error
            messages).
        series : InfluentSeries
            The time-varying influent data.
        to : str, optional
            Destination endpoint to feed this influent into, as ``"unit.port"``
            (or bare ``"unit"`` to use the unit's sole input port). When given,
            the connection is made here, so no separate :meth:`connect` call is
            needed. The destination unit must already be added. When omitted it
            defaults to the plant's :attr:`influent_endpoint` (set by the
            builders, so ``plant.add_influent("feed", series)`` wires to the
            canonical front without hard-coding a port); if that is also unset
            the influent is registered but inert -- influents are not valid
            :meth:`connect` sources, so wiring happens here.
        translator : StateTranslator, optional
            Translator for the influent -> unit connection. Defaults to identity
            when the influent and destination share a model.
        """
        check_name("influent", name)
        if name in self.units:
            raise WiringError(f"influent name '{name}' is already the name of a unit")
        if name in self.named_streams:
            raise WiringError(f"influent name '{name}' is already the name of a stream")
        if name in self.influents:
            raise ValueError(f"Influent '{name}' already added")
        self._influents_added[name] = series
        self.influents[name] = series.in_time_unit(self._declared_time_unit)
        if to is None:
            to = self.influent_endpoint
        if to is not None:
            to_unit, to_port = self._parse_endpoint(to, role="destination")
            translator = self._default_translator(
                series.model,
                to_unit,
                translator,
                f"influent '{name}'",
                f"{to_unit}.{to_port}",
            )
            self.connections.append(
                Connection(
                    from_unit=None,
                    from_port=name,
                    to_unit=to_unit,
                    to_port=to_port,
                    translator=translator,
                    initial_value=None,
                )
            )
        self._structure_changed()

    def set_temperature(self, celsius: float, *, units: Iterable[str] | None = None) -> Plant:
        """Set the operating temperature of the reactors, in **degrees Celsius**.

        One knob for "run the plant at this temperature": converts to Kelvin and
        writes the static ``T`` condition of every temperature-bearing reactor,
        so a re-solve runs the kinetics -- including the Arrhenius
        ``temperature_corrections`` -- at that temperature. (For a model whose
        corrections are referenced to this temperature, the correction is unity
        and the run reproduces the calibrated operating point; a colder/warmer
        setting drives the kinetics away from it.)

        By default it targets the activated-sludge reactors (the units exposing
        :meth:`CSTRUnit.set_temperature` with a ``T`` condition) and **leaves a
        fixed-temperature unit like the heated anaerobic digester untouched** --
        the digester is a separate ADM1 unit without that method. Pass ``units``
        to target a specific set by name.

        Parameters
        ----------
        celsius : float
            Operating temperature in °C (converted to Kelvin internally; the
            ASM/ADM condition fields are Kelvin).
        units : iterable of str, optional
            Unit names to set. Defaults to every reactor that supports it.

        Returns
        -------
        Plant
            ``self`` (so calls can be chained after ``build_*``).

        Raises
        ------
        UnknownUnitError
            If a name in ``units`` is not a unit of this plant.
        WiringError
            If a named unit does not support a temperature (e.g. a separator).
        """
        kelvin = float(celsius) + 273.15
        if units is None:
            targets = [
                n
                for n, u in self.units.items()
                if isinstance(u, TemperatureSettable)
                and "T" in getattr(u.model, "conditions_required", ())
            ]
        else:
            targets = list(units)
            for name in targets:
                if name not in self.units:
                    raise UnknownUnitError(f"Unknown unit '{name}'.")
                if not isinstance(self.units[name], TemperatureSettable):
                    raise WiringError(f"Unit '{name}' does not support set_temperature.")
        for name in targets:
            self.units[name].set_temperature(kelvin)
        # The compiled solves bake in the (now-changed) condition values, so they
        # must be recompiled on the next solve. The colored-Jacobian pattern is a
        # structural property of the (unchanged) state layout, so it stays valid.
        self._solve_cache.invalidate()
        return self

    def set_temperature_model(self, model: TemperatureModel) -> Plant:
        """Select how reactor temperature is handled (see :mod:`aquakin.plant.temperature`).

        Pass :class:`~aquakin.plant.temperature.HeatBalanceTemperature` to give
        each finite-volume liquid unit a dynamic temperature state (a first-order
        heat balance), or the default
        :class:`~aquakin.plant.temperature.AlgebraicTemperature` for the
        instantaneous flow-weighted behaviour. Changes the flat state-vector
        length (an appended temperature block), so it clears the compiled-solve
        cache; rebuild ``y0`` (e.g. via ``bsm2_warm_start``) after calling it.
        Returns ``self`` for chaining.
        """
        self.temperature_model = model
        # Changing the temperature model changes the flat state length (an
        # appended temperature block), so both the compiled solves and the
        # structural colored-Jacobian builders (which cache seed matrices /
        # patterns sized for the concrete state) are stale -- invalidate both
        # (unlike set_temperature, which leaves the state size and pattern
        # unchanged and so keeps the colored builders).
        self._solve_cache.invalidate()
        self._colored.reset()
        return self

    def connect(
        self,
        source: str,
        dest: str,
        *,
        translator: StateTranslator | None = None,
        initial_value: Stream | None = None,
    ) -> None:
        """Wire a stream from one unit's output to another unit's input.

        Both endpoints are ``"unit.port"`` strings, read as ``source -> dest``.
        The port may be omitted (bare ``"unit"``) when the unit has exactly one
        port for that role -- a single output (source) or single input (dest) --
        so only multi-port units like mixers and splitters need an explicit
        port. To feed an external influent, use
        :meth:`add_influent` with ``to=...`` rather than :meth:`connect`.

        Parameters
        ----------
        source : str
            Source endpoint, ``"unit.port"`` or bare ``"unit"`` for the unit's
            sole output port.
        dest : str
            Destination endpoint, ``"unit.port"`` or bare ``"unit"`` for the
            unit's sole input port.
        translator : StateTranslator, optional
            State translator to apply as the stream crosses the connection.
            Defaults to :class:`IdentityTranslator` when source and destination
            share a model; required when they differ.
        initial_value : Stream, optional
            Seed for the stream's first RHS pass on a *recycle* edge. Recycles
            are detected automatically as the back-edges of the connection graph
            (you do not mark them, and the units may be added in any order); a
            recycle with no ``initial_value`` is auto-seeded with a zero-flow
            stream of the source model. Pass it only to override that with a
            non-zero warm start (e.g. a temperature-carrying seed to ignite
            temperature propagation around the loop on the first pass). Ignored
            for feed-forward edges. Both endpoints must already be added.

        Examples
        --------
        >>> plant.connect("tank1", "tank2")                 # sole ports inferred
        >>> plant.connect("tank5_split.to_clarifier", "clarifier")
        >>> plant.connect("split.recycle", "mix.recycle")   # recycle: auto-detected
        """
        src_unit, src_port = self._parse_endpoint(source, role="source")
        dst_unit, dst_port = self._parse_endpoint(dest, role="destination")
        translator = self._default_translator(
            self._unit_model(src_unit),
            dst_unit,
            translator,
            f"{src_unit}.{src_port}",
            f"{dst_unit}.{dst_port}",
        )
        self.connections.append(
            Connection(
                from_unit=src_unit,
                from_port=src_port,
                to_unit=dst_unit,
                to_port=dst_port,
                translator=translator,
                initial_value=initial_value,
            )
        )
        self._structure_changed()

    def check(self, *, raise_on_error: bool = False) -> PlantCheck:
        """Validate the plant before solving: wiring and declared units.

        Every unit input port must be fed by exactly one stream (an influent or
        another unit's output); an **unfed** input port has no source, so the RHS
        sweep cannot resolve it and the solve fails. Output ports consumed by no
        connection are reported too, but as information -- a terminal stream that
        leaves the plant (final effluent, wasted sludge, disposal cake, biogas)
        is legitimately unconsumed. The findings of :meth:`check_units` are
        included as well: its errors count as errors here, its warnings do not.

        Parameters
        ----------
        raise_on_error : bool, optional
            If True, raise ``ValueError`` when any input port is unfed, or
            :class:`UnitsError` (a ``ValueError``) when the unit audit finds an
            error, instead of only reporting it. Default False.

        Returns
        -------
        PlantCheck
            ``unfed_ports`` (errors), ``dangling_outputs`` (info), ``recycles``
            (the detected back-edges), ``unit_issues`` (the unit audit), with
            ``.ok`` (no unfed port and no unit error) and ``.summary()``.
        """
        self._finalize_topology()
        fed = {(c.to_unit, c.to_port) for c in self.connections}
        consumed = {(c.from_unit, c.from_port) for c in self.connections if c.from_unit is not None}
        unfed, dangling = [], []
        for name in self._insertion_order:
            unit = self.units[name]
            for port in unit.input_ports:
                if (name, port) not in fed:
                    unfed.append(f"{name}.{port}")
            for port in unit.output_ports:
                if (name, port) not in consumed:
                    dangling.append(f"{name}.{port}")
        result = PlantCheck(
            unfed_ports=unfed,
            dangling_outputs=dangling,
            recycles=[f"{u}.{p}" for (u, p) in self._recycle_keys],
            unit_issues=self.check_units().issues,
        )
        if raise_on_error and unfed:
            raise ValueError(
                f"Plant '{self.name}' has unfed input ports (no stream wired "
                f"in): {unfed}. Wire them with connect()/add_influent() before "
                f"solving."
            )
        if raise_on_error and result.unit_errors:
            raise UnitsError(
                f"Plant '{self.name}' has inconsistent units:\n"
                + "\n".join(f"  {i}" for i in result.unit_errors)
            )
        return result

    def check_units(self, *, include_models: bool = True) -> PlantUnitsReport:
        """Audit the plant's declared units for consistency, before solving.

        The plant integrates every unit against one clock (:attr:`time_unit`),
        converting each model's rates, each influent's times and flows and the
        unit operations' built-in time constants to it, but it passes stream
        concentrations between units unconverted, so a concentration mismatch
        is silent. This compares the units the plant's parts *declare*:

        - on a plant created without ``time_unit`` (deprecated), every kinetic
          model's time unit (:attr:`CompiledModel.time_unit`), which must
          agree, and a warning for a model whose time unit cannot be inferred;
        - species whose concentration basis a unit's constants fix (e.g. a
          settler's ``g/m3`` settling parameters) against the model's units;
        - each model's own rate-expression check
          (:meth:`CompiledModel.check_units`), as warnings.

        Comparisons are scale-aware (``mg/L`` matches ``g/m3``; ``kg/m3`` does
        not). Blank or unparseable units are skipped. Models that disagree on a
        plant without ``time_unit`` also make :meth:`solve` raise
        :class:`UnitsError`; everything else here is reported, not raised.
        :meth:`check` includes this report.

        Parameters
        ----------
        include_models : bool, default True
            Also report each model's rate-expression findings as warnings.

        Returns
        -------
        PlantUnitsReport
            ``errors`` / ``warnings`` lists of :class:`PlantUnitIssue`, ``ok``,
            the plant ``time_unit`` and a ``summary()``.

        Examples
        --------
        >>> plant = build_bsm2()
        >>> print(plant.check_units().summary())
        Plant units: OK (time unit: d)
        """
        return check_plant_units(self, include_models=include_models)

    def _parse_endpoint(self, spec: str, *, role: str) -> tuple[str, str]:
        """Resolve a ``"unit.port"`` / ``"unit"`` endpoint string to ``(unit, port)``.

        ``role`` is ``"source"`` (resolves against the unit's output ports) or
        ``"destination"`` (input ports). A bare unit infers its sole port for
        that role; an unknown unit, an unknown port, or an ambiguous bare unit
        (more than one port for the role) raises a clear error.
        """
        unit_name, _, port = spec.partition(".")
        if unit_name not in self.units:
            if unit_name in self.influents:
                raise WiringError(
                    f"'{unit_name}' is an influent, not a unit; wire it with "
                    f"add_influent('{unit_name}', series, to=...), not connect()."
                )
            raise UnknownUnitError(f"Unknown unit '{unit_name}' in endpoint '{spec}'.")
        ports = (
            self.units[unit_name].output_ports
            if role == "source"
            else self.units[unit_name].input_ports
        )
        if port:
            if port not in ports:
                raise UnknownPortError(
                    f"Unit '{unit_name}' has no {role} port '{port}'; available: {list(ports)}."
                )
            return unit_name, port
        if len(ports) != 1:
            raise WiringError(
                f"Endpoint '{spec}' omits the port, but unit '{unit_name}' has "
                f"{len(ports)} {role} ports {list(ports)}; name one explicitly "
                f"as '{unit_name}.<port>'."
            )
        return unit_name, ports[0]

    def _default_translator(
        self, source_model, dest_unit, translator, src_label, dst_label
    ) -> StateTranslator:
        """Return ``translator`` if given, else the default for the endpoints.

        The default is :class:`IdentityTranslator` when the source and
        destination share a model, and a :class:`UnitScalingTranslator` when
        their models list the same species in the same order but declare some
        of them in different units. Any other cross-model connection with no
        explicit translator is an error.
        """
        if translator is not None:
            self._check_translator_endpoints(
                translator,
                source_model,
                getattr(self.units[dest_unit], "model", None),
                src_label,
                dst_label,
            )
            return translator
        target_model = self._unit_model(dest_unit)
        if source_model is target_model:
            return IdentityTranslator(target_model)
        if _same_species_other_units(source_model, target_model):
            try:
                return UnitScalingTranslator(source_model, target_model)
            except ValueError as exc:
                raise WiringError(
                    f"Connection {src_label} -> {dst_label}: models "
                    f"'{getattr(source_model, 'name', '?')}' and "
                    f"'{getattr(target_model, 'name', '?')}' list the same species "
                    f"in different units that cannot be converted ({exc}); supply "
                    f"an explicit translator."
                ) from None
        # Two *different* model objects. Distinguish the common mistake -- two
        # separate instances of the same model (e.g. calling bsm2_asm1_model()
        # twice, so the plant and the influent carry different temperature
        # corrections / parameters) -- from a genuine cross-model connection.
        same_model = getattr(source_model, "name", object()) == getattr(
            target_model, "name", None
        ) and getattr(source_model, "species", object()) == getattr(target_model, "species", None)
        if same_model:
            raise ValueError(
                f"Connection {src_label} -> {dst_label}: the two endpoints use "
                f"different *instances* of the same model "
                f"('{getattr(source_model, 'name', '?')}'). Build the model "
                f"once and pass that same object to both the plant and the "
                f"influent, so their parameters and temperature corrections "
                f"match -- two instances are silently inconsistent. (If they are "
                f"genuinely different models, pass an explicit translator=.)"
            )
        raise ValueError(
            f"Connection {src_label} -> {dst_label} crosses models "
            f"('{getattr(source_model, 'name', '?')}' -> "
            f"'{getattr(target_model, 'name', '?')}'); supply an explicit "
            f"translator."
        )

    @staticmethod
    def _check_translator_endpoints(
        translator, source_model, target_model, src_label, dst_label
    ) -> None:
        """Reject an explicit translator built for different models than the
        ones it connects. A translator reads and writes species by index and
        converts from the units its models declare, so a source or target model
        with a different species list, or with a species declared in other
        units, silently scrambles or rescales the stream. A different *instance*
        with the same species and units is accepted."""
        for side, declared, actual in (
            ("source", getattr(translator, "source_model", None), source_model),
            ("target", getattr(translator, "target_model", None), target_model),
        ):
            if declared is None or actual is None or declared is actual:
                continue
            if list(declared.species) != list(actual.species):
                raise WiringError(
                    f"Connection {src_label} -> {dst_label}: the translator's "
                    f"{side} model is '{declared.name}', but the {side} of this "
                    f"connection uses model '{actual.name}' with a different "
                    f"species list. Build the translator with the models it "
                    f"connects."
                )
            for species in actual.species:
                built = declared.species_units.get(species, "")
                used = actual.species_units.get(species, "")
                if units_match(built, used) is False:
                    raise WiringError(
                        f"Connection {src_label} -> {dst_label}: the translator "
                        f"was built for a {side} model declaring '{species}' in "
                        f"'{built}', but the {side} of this connection declares "
                        f"it in '{used}'. Build the translator with the models it "
                        f"connects."
                    )

    def _finalize_topology(self) -> None:
        """Compute the RHS evaluation order and the recycle (back-edge) set.

        Topologically sorts the feed-forward connection graph so units can be
        added in any order. A connection carrying an explicit ``initial_value``
        is treated as a declared recycle and cut first (so its seed sits on the
        cut edge); any cycle remaining in the rest is broken deterministically --
        Kahn's algorithm with an insertion-order tie-break, and when it stalls
        the earliest-added remaining unit has its still-active incoming edges cut
        (those become auto-detected recycles, zero-flow seeded). Sets
        :attr:`_unit_order`, :attr:`_recycle_keys`, :attr:`_recycle_conns` and the
        zero-flow :attr:`_recycle_seeds`. Deterministic, so the state/parameter
        layouts are stable, and for a plant whose units were already added in a
        valid evaluation order it reproduces that order and recycle set exactly.
        """
        units = self._insertion_order
        pos = {u: i for i, u in enumerate(units)}
        unit_conns = [c for c in self.connections if c.from_unit is not None]
        forced_ids = {id(c) for c in unit_conns if c.initial_value is not None}

        incoming = {u: [] for u in units}
        succ = {u: [] for u in units}
        for c in unit_conns:
            if id(c) not in forced_ids:
                incoming[c.to_unit].append(c)
                succ[c.from_unit].append(c)
        indeg = {u: len(incoming[u]) for u in units}

        remaining = set(units)
        cut_ids: set[int] = set()
        order: list[str] = []
        while remaining:
            ready = sorted((u for u in remaining if indeg[u] == 0), key=pos.get)
            if not ready:
                # Cycle: break it at the earliest-added remaining unit by cutting
                # its still-active incoming edges (sources not yet emitted).
                node = min(remaining, key=pos.get)
                for c in incoming[node]:
                    if c.from_unit in remaining and id(c) not in cut_ids:
                        cut_ids.add(id(c))
                        indeg[node] -= 1
                ready = [node]
            node = ready[0]
            order.append(node)
            remaining.discard(node)
            for c in succ[node]:
                if id(c) not in cut_ids and c.to_unit in remaining:
                    indeg[c.to_unit] -= 1

        self._unit_order = order
        forced = [c for c in unit_conns if id(c) in forced_ids]
        auto_cut = [c for c in unit_conns if id(c) in cut_ids]
        self._recycle_conns = forced + auto_cut
        self._recycle_keys = [(c.from_unit, c.from_port) for c in self._recycle_conns]
        self._recycle_seeds = {}
        for c in auto_cut:
            net = self.units[c.from_unit].model
            self._recycle_seeds[(c.from_unit, c.from_port)] = Stream(
                Q=jnp.asarray(0.0), C=net.default_concentrations(), model=net
            )

    def _unit_model(self, unit_name: str) -> CompiledModel:
        unit = self.units[unit_name]
        if not hasattr(unit, "model"):
            raise KeyError(
                f"Unit '{unit_name}' has no 'model' attribute; cannot infer translator default."
            )
        return unit.model

