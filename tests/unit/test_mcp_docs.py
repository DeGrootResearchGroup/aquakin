"""The user guide as ``aquakin mcp`` serves it: which pages are published, where
an installation finds them, and reading and searching them."""

from __future__ import annotations

import importlib.util
import re
from pathlib import Path

import pytest

from aquakin.mcp import docs

DOCS = Path(__file__).resolve().parents[2] / "docs"


@pytest.fixture
def guide(tmp_path):
    """The pages of a built package's layout, with two bundled pages."""
    bundle = tmp_path / docs.BUNDLE
    bundle.mkdir()
    (bundle / "alpha.md").write_text(
        "# Alpha page\n\nIntro on fisher.\n\n"
        "## Fitting\n\nFit with calibrate.\n\n```python\n# Not a heading\nx = 1\n```\n\n"
        "### Fitting detail\n\nDeeper calibrate text.\n\n"
        "## Designing\n\nFisher information and design. Fisher again.\n",
        encoding="utf-8",
    )
    (bundle / "beta.md").write_text(
        "# Beta page\n\n## Only fisher\n\nfisher fisher fisher fisher fisher.\n",
        encoding="utf-8",
    )
    return docs.guide_pages(tmp_path)


def test_published_pages_are_the_markdown_files_conf_does_not_exclude(tmp_path):
    (tmp_path / "conf.py").write_text('project = "x"\nexclude_patterns = ["_build", "dev.md"]\n')
    for name in ("b.md", "a.md", "dev.md", "notes.txt"):
        (tmp_path / name).write_text("# t\n")
    assert [p.name for p in docs.published_pages(tmp_path)] == ["a.md", "b.md"]


def test_a_conf_without_exclude_patterns_is_refused(tmp_path):
    (tmp_path / "conf.py").write_text('project = "x"\n')
    with pytest.raises(ValueError, match="has no exclude_patterns list"):
        docs.published_pages(tmp_path)


def test_the_real_guide_publishes_every_toctree_page_and_no_dev_log():
    published = {p.stem for p in docs.published_pages(DOCS)}
    linked = {"index"}
    for page in DOCS.glob("*.md"):
        for block in re.findall(r"```\{toctree\}(.*?)```", page.read_text(), re.S):
            linked |= {ln.strip() for ln in block.splitlines() if ln.strip() and ":" not in ln}
    assert linked - {"api"} <= published  # api.md is generated by Sphinx, not a file
    assert not {"ci", "plant_performance", "package_structure", "project_reference"} & published


def test_a_source_checkout_reads_its_docs_folder():
    pages = {entry["page"] for entry in docs.list_pages()}
    assert pages == {p.stem for p in docs.published_pages(DOCS)}
    assert docs.guide_pages() == {p.stem: p for p in docs.published_pages(DOCS)}


def test_a_built_package_reads_its_bundled_pages(guide, tmp_path):
    assert guide == {
        "alpha": tmp_path / docs.BUNDLE / "alpha.md",
        "beta": tmp_path / docs.BUNDLE / "beta.md",
    }
    assert docs.list_pages(guide) == [
        {"page": "alpha", "title": "Alpha page"},
        {"page": "beta", "title": "Beta page"},
    ]


def test_an_installation_without_pages_says_where_to_read_them(tmp_path):
    package_dir = tmp_path / "aquakin" / "mcp"
    package_dir.mkdir(parents=True)
    with pytest.raises(FileNotFoundError, match=r"aquakin\.readthedocs\.io"):
        docs.guide_pages(package_dir)


def test_the_module_loads_by_path_as_setup_py_loads_it():
    """``setup.py`` loads it by path while building, before aquakin is importable."""
    spec = importlib.util.spec_from_file_location("_guide_by_path", docs.__file__)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    assert module.published_pages(DOCS) == docs.published_pages(DOCS)


def test_a_section_runs_to_the_next_heading_of_its_level_and_skips_code_comments(guide):
    text = docs.read_page("alpha.md", section="fitting", pages=guide)
    assert text.startswith("## Fitting\n")
    assert "# Not a heading" in text  # the code block stays in its section
    assert "Deeper calibrate text." in text  # the subsection is included
    assert "## Designing" not in text
    assert docs.read_page("alpha", pages=guide) == guide["alpha"].read_text()
    # The last section runs to the end of the page.
    assert docs.read_page("alpha", section="Designing", pages=guide) == (
        "## Designing\n\nFisher information and design. Fisher again.\n"
    )


def test_an_unknown_page_or_section_lists_what_there_is(guide):
    with pytest.raises(KeyError, match=r"no guide page 'gamma'; the pages are \['alpha', 'beta'\]"):
        docs.read_page("gamma", pages=guide)
    with pytest.raises(KeyError, match=r"its headings are \['Alpha page', 'Fitting', 'Fitting"):
        docs.read_page("alpha", section="Not a heading", pages=guide)


def test_search_ranks_sections_with_every_word_first(guide):
    hits = docs.search("Fisher design", limit=10, pages=guide)
    # alpha/Designing holds both words: "fisher" twice, "design" twice (once
    # inside its heading "Designing"). beta's section has "fisher" six times
    # (its heading included) but no "design", so it ranks after; alpha's intro
    # has one "fisher". A heading is part of its section's text.
    assert [(h["page"], h["section"], h["score"]) for h in hits] == [
        ("alpha", "Designing", 4),
        ("beta", "Only fisher", 6),
        ("alpha", "Alpha page", 1),
    ]
    assert hits[0]["snippet"].startswith("## Designing Fisher information")
    assert [h["section"] for h in docs.search("fisher", limit=1, pages=guide)] == ["Only fisher"]


def test_text_above_the_first_heading_is_reported_as_no_section(tmp_path):
    (tmp_path / "gamma.md").write_text("Loose zeta text.\n")
    assert docs.search("zeta", pages={"gamma": tmp_path / "gamma.md"}) == [
        {"page": "gamma", "section": None, "score": 1, "snippet": "Loose zeta text."}
    ]


def test_a_search_needs_words_and_a_positive_limit(guide):
    with pytest.raises(ValueError, match="no words"):
        docs.search(" ?! ", pages=guide)
    with pytest.raises(ValueError, match="limit must be at least 1, not 0"):
        docs.search("fisher", limit=0, pages=guide)
